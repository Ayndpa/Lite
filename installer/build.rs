// Build steps for the installer:
// 1. theme.slint — the app's color themes (ui/themes/*.json) as a Slint global, so the installer
//    looks like Lite and follows theme changes without a second palette to maintain.
// 2. payload.zip — the release build of the app plus plugins/, embedded into the executable.
// 3. The Slint UI, and on Windows the executable's icon.
use std::{
    env, fs,
    io::Write,
    path::{Path, PathBuf},
};

/// Theme tokens the installer uses: (Slint property, token in ui/themes/*.json).
const TOKENS: &[(&str, &str)] = &[
    ("bg", "bg"),
    ("surface", "surface"),
    ("titlebar", "titlebar.bg"),
    ("fg", "fg"),
    ("fg-strong", "fg.strong"),
    ("fg-muted", "fg.muted"),
    ("fg-dim", "fg.dim"),
    ("accent", "accent"),
    ("logo", "logo"),
    ("hover", "hover"),
    ("active", "active"),
    ("border", "border"),
    ("border-subtle", "border.subtle"),
    ("primary", "primary"),
    ("primary-hover", "primary.hover"),
    ("primary-fg", "primary.fg"),
    ("control-bg", "control.bg"),
    ("control-hover", "control.hover"),
    ("control-border", "control.border"),
    ("input-bg", "input.bg"),
    ("error", "error"),
    ("success", "success"),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.parent().unwrap().to_path_buf();
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    write_theme(&root.join("ui").join("themes"), &out.join("theme.slint"));
    write_payload(&root, &out.join("payload.zip"));

    let conf: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(root.join("src-tauri").join("tauri.conf.json")).unwrap()).unwrap();
    println!("cargo:rustc-env=LITE_VERSION={}", conf["version"].as_str().unwrap());
    println!("cargo:rerun-if-changed=../src-tauri/tauri.conf.json");

    let config = slint_build::CompilerConfiguration::new().with_include_paths(vec![out.clone()]);
    slint_build::compile_with_config("ui/app.slint", config).unwrap();

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let mut res = winresource::WindowsResource::new();
        res.set_icon(root.join("src-tauri").join("icons").join("icon.ico").to_str().unwrap());
        res.set("ProductName", "Lite");
        res.set("FileDescription", "Lite Setup");
        res.compile().unwrap();
    }
}

// ---------- theme ----------

/// A CSS color as Slint's #rrggbbaa. Gradients (the app's window background) become their middle stop.
fn slint_color(css: &str) -> String {
    let css = css.trim();
    if css.contains("gradient(") {
        let stops: Vec<&str> = css.split(|c: char| c == ' ' || c == ',' || c == '(' || c == ')').filter(|s| s.starts_with('#')).collect();
        return slint_color(stops[stops.len() / 2]);
    }
    if let Some(hex) = css.strip_prefix('#') {
        return match hex.len() {
            3 => format!("#{}ff", hex.chars().flat_map(|c| [c, c]).collect::<String>()),
            6 => format!("#{hex}ff"),
            8 => format!("#{hex}"),
            _ => panic!("unsupported color: {css}"),
        };
    }
    if let Some(args) = css.strip_prefix("rgba(").or_else(|| css.strip_prefix("rgb(")).and_then(|s| s.strip_suffix(')')) {
        let n: Vec<f64> = args.split(',').map(|v| v.trim().parse().unwrap()).collect();
        let alpha = n.get(3).copied().unwrap_or(1.0);
        return format!("#{:02x}{:02x}{:02x}{:02x}", n[0] as u8, n[1] as u8, n[2] as u8, (alpha * 255.0).round() as u8);
    }
    panic!("unsupported color: {css}");
}

fn write_theme(themes: &Path, dest: &Path) {
    let load = |name: &str| -> serde_json::Value {
        let file = themes.join(format!("{name}.json"));
        println!("cargo:rerun-if-changed={}", file.display());
        serde_json::from_str(&fs::read_to_string(&file).unwrap()).unwrap()
    };
    let (dark, light) = (load("dark"), load("light"));
    let color = |theme: &serde_json::Value, token: &str| {
        slint_color(theme["colors"][token].as_str().unwrap_or_else(|| panic!("theme token missing: {token}")))
    };
    let mut s = String::from(
        "// Generated by build.rs from ui/themes/dark.json and light.json.\n\
         // Lite starts in its dark theme whatever the system setting, so the installer does too.\n\
         export global Theme {\n    \
         in property <bool> dark: true;\n",
    );
    for (prop, token) in TOKENS {
        s += &format!("    out property <color> {prop}: dark ? {} : {};\n", color(&dark, token), color(&light, token));
    }
    s += "}\n";
    fs::write(dest, s).unwrap();
}

// ---------- payload ----------

/// What gets installed: the app executable and plugins/ — without per-user state and without the
/// plugins' unbundled sources (plugins/<id>/src), which the app never loads.
fn write_payload(root: &Path, dest: &Path) {
    println!("cargo:rerun-if-env-changed=LITE_EXE");
    let exe_name = if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") { "lite.exe" } else { "lite" };
    let exe = env::var_os("LITE_EXE")
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("src-tauri").join("target").join("release").join(exe_name));
    if !exe.is_file() {
        panic!("{} not found: build the app first (cargo build --release in src-tauri), or set LITE_EXE", exe.display());
    }
    println!("cargo:rerun-if-changed={}", exe.display());
    let plugins = root.join("plugins");
    println!("cargo:rerun-if-changed={}", plugins.display());

    let mut files = vec![(exe_name.to_string(), exe)];
    collect(&plugins, "plugins", &mut files);
    files.sort();

    let mut zip = zip::ZipWriter::new(fs::File::create(dest).unwrap());
    let options = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated).compression_level(Some(9));
    for (name, path) in files {
        zip.start_file(name, options).unwrap();
        zip.write_all(&fs::read(path).unwrap()).unwrap();
    }
    zip.finish().unwrap();
}

fn collect(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) {
    for entry in fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        let name = entry.file_name().to_string_lossy().into_owned();
        let rel = format!("{prefix}/{name}");
        if entry.file_type().unwrap().is_dir() {
            // plugins/<id>/src: sources that tools/build.mjs bundles into plugins/<id>/*.js
            if name == "src" && prefix.matches('/').count() == 1 {
                continue;
            }
            collect(&entry.path(), &rel, files);
        } else if rel != "plugins/state.json" {
            files.push((rel, entry.path()));
        }
    }
}
